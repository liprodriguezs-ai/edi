<?php

declare(strict_types=1);

namespace Tests\Feature\ChildRecord;

use Illuminate\Foundation\Testing\RefreshDatabase;
use Modules\ChildRecord\Models\Child;
use Modules\ChildRecord\Models\Sex;
use Modules\ChildRecord\Models\Visit;
use Modules\Clinic\Database\Factories\HealthCenterFactory;
use Modules\Clinic\Models\HealthCenter;
use Modules\Clinic\Models\PractitionerProfile;
use Tests\Support\WithTenantSetup;
use Tests\TestCase;

/**
 * A practitioner's NAME lives on their user, not on the profile row, so every
 * screen that shows "Profesional" reads practitioner.user.name. The visit resource
 * only allowed the `practitioner` relation, so that name resolved to undefined and
 * the column rendered "—" on every row while the data was there all along.
 */
final class VisitIncludeContractTest extends TestCase
{
    use RefreshDatabase;
    use WithTenantSetup;

    /** @var array<string> */
    protected $connectionsToTransact = [];

    protected function tearDown(): void
    {
        if (tenancy()->initialized) {
            tenancy()->end();
        }

        parent::tearDown();
    }

    public function test_visit_can_include_the_practitioner_user_so_the_name_resolves(): void
    {
        [$tenantA, $tokenA] = $this->twoTenants();

        $this->inTenant($tenantA, function (): void {
            $municipality = HealthCenterFactory::defaultMunicipality();
            $healthCenter = HealthCenter::factory()->create(['municipality_id' => $municipality->id]);
            $practitioner = PractitionerProfile::factory()->create(['health_center_id' => $healthCenter->id]);

            $child = Child::create([
                'first_name' => 'Diego',
                'last_name_paternal' => 'Prueba',
                'birth_date' => '2025-01-15',
                'sex_id' => Sex::query()->value('id'),
                'health_center_id' => $healthCenter->id,
            ]);

            // receipt_number is generated by VisitService, which this test bypasses.
            Visit::create([
                'child_id' => $child->id,
                'health_center_id' => $healthCenter->id,
                'practitioner_id' => $practitioner->id,
                'visit_date' => '2025-06-01',
                'receipt_number' => 'R-2025-000001',
            ]);
        });

        $response = $this->tenantRequest($tokenA, $tenantA)
            ->getJson('/api/visit?include=practitioner.user')
            ->assertOk();

        $this->assertNotNull(
            $response->json('data.0.practitioner.user.name'),
            'The practitioner user did not load, so every "Profesional" cell renders a dash.'
        );
    }
}
