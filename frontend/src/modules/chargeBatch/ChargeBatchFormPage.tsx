import { Button } from '@/components/ui/button'
import { Field, FieldDescription, FieldError, FieldGroup, FieldLabel } from '@/components/ui/field'
import { Input } from '@/components/ui/input'
import { RadioGroup, RadioGroupItem } from '@/components/ui/radio-group'
import { Textarea } from '@/components/ui/textarea'
import { MONTH_NAMES, MonthYearSelector } from '@/modules/chargeBatch/components/MonthYearSelector'
import {
  PolicySummaryPanel,
  policyOptionLabel,
} from '@/modules/chargeBatch/components/PolicySummaryPanel'
import { SingleTargetSelector } from '@/shared/components/target/SingleTargetSelector'
import { buildChargeBatchDefaults } from '@/modules/chargeBatch/constants'
import {
  buildTargetSelector,
  chargeBatchFormSchema,
  type ChargeBatchFormValues,
  type IChargeBatch,
} from '@/modules/chargeBatch/schema'
import { ChargeBatchResource } from '@/modules/chargeBatch/services/ChargeBatchResource'
import {
  isAutoGenerated,
  periodicityCadenceLabel,
} from '@/modules/chargeConcept/helpers/chargeGeneration'
import { type IChargePolicy } from '@/modules/chargePolicy/schema'
import { ConfigurationResource } from '@/modules/configuration/services/ConfigurationResource'
import { ApiError, formatApiErrorMessage } from '@/shared/api/apiClient'
import { Callout } from '@/shared/components/atoms/Callout'
import { ChargeLifecycleTimeline } from '@/shared/components/molecules/ChargeLifecycleTimeline'
import { RequiredFieldsLegend } from '@/shared/components/RequiredFieldsLegend'
import { SearchSelect } from '@/shared/components/SearchSelect'
import { CatalogType, useCatalogs } from '@/shared/hooks/useCatalogs'
import { toast } from '@/shared/hooks/useToast'
import {
  computeConcreteLifecycleMilestones,
  resolveTimingSettings,
} from '@/shared/utils/chargeLifecycle'
import { zodResolver } from '@hookform/resolvers/zod'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { ArrowLeft, RefreshCw } from 'lucide-react'
import { useEffect, useMemo, useState } from 'react'
import { Controller, useForm, useWatch } from 'react-hook-form'
import { Link, useNavigate } from 'react-router-dom'

const SECTION = 'rounded-[14px] border border-border bg-card p-5 shadow-sm'
const SECTION_TITLE =
  'mb-4 text-[11px] font-semibold uppercase tracking-[0.08em] text-[var(--ink-3)]'

/**
 * Nuevo cobro en PÁGINA COMPLETA: se elige una POLÍTICA (no un concepto). El monto,
 * periodicidad y gracia se HEREDAN de la política y se muestran en un panel de solo
 * lectura — el lote ya no define su propio monto (sin override). Alcance + fechas +
 * activar/borrador como antes.
 */
export const ChargeBatchFormPage = () => {
  const navigate = useNavigate()
  const queryClient = useQueryClient()

  const {
    register,
    handleSubmit,
    reset,
    control,
    watch,
    setValue,
    formState: { errors },
  } = useForm<ChargeBatchFormValues>({
    resolver: zodResolver(chargeBatchFormSchema),
    defaultValues: buildChargeBatchDefaults(new Date()),
  })

  useEffect(() => {
    reset(buildChargeBatchDefaults(new Date()))
  }, [reset])

  const { catalogs } = useCatalogs(
    useMemo(
      () => ({
        [CatalogType.CHARGE_POLICY]: { _sort: 'name', _with: 'concept,periodicity' },
        [CatalogType.UNIT_TYPE]: { _sort: 'order' },
        [CatalogType.TOWER]: { _sort: 'order' },
        [CatalogType.SECTION]: { _sort: 'order' },
        [CatalogType.UNIT_FEATURE]: { _sort: 'name' },
      }),
      []
    )
  )

  const targetType = watch('target_type')
  const policyId = watch('charge_policy_id')
  const year = watch('year')
  const month = watch('month')
  const [singleUnitLabel, setSingleUnitLabel] = useState('')

  const policies = (catalogs[CatalogType.CHARGE_POLICY] ?? []) as IChargePolicy[]
  const selectedPolicy = policies.find((policy) => policy.id === policyId)

  const { data: collectionSettings } = useQuery({
    queryKey: ['config', 'collection-settings'],
    queryFn: () => ConfigurationResource.getCollectionSettings(),
    staleTime: 5 * 60 * 1000,
    retry: false,
  })

  // El título se autocompleta del concepto de la política + periodo.
  useEffect(() => {
    if (!selectedPolicy) return
    const label = selectedPolicy.concept?.name ?? selectedPolicy.name
    const period = month ? `${MONTH_NAMES[month - 1]} ${year}` : String(year)
    setValue('title', `${label} ${period}`)
  }, [selectedPolicy, month, year, setValue])

  // Preview del alcance: se suscribe SOLO a los campos de alcance via useWatch (no a todo
  // el form con watch()), evitando un re-render de la pagina en cada tecla de cualquier campo.
  const targetFields = useWatch({
    control,
    name: [
      'target_type',
      'target_unit_type_ids',
      'target_tower_ids',
      'target_section_ids',
      'target_floor',
      'target_feature_ids',
      'target_unit_id',
      'target_unit_ids',
    ],
  })
  const previewSelector = useMemo(() => {
    const [
      target_type,
      target_unit_type_ids,
      target_tower_ids,
      target_section_ids,
      target_floor,
      target_feature_ids,
      target_unit_id,
      target_unit_ids,
    ] = targetFields
    // buildTargetSelector solo lee los campos de alcance; el resto de ChargeBatchFormValues
    // no interviene, por eso construimos un objeto parcial y lo tipamos al form.
    return buildTargetSelector({
      target_type,
      target_unit_type_ids,
      target_tower_ids,
      target_section_ids,
      target_floor,
      target_feature_ids,
      target_unit_id,
      target_unit_ids,
    } as ChargeBatchFormValues)
  }, [targetFields])

  const issuedAt = watch('issued_at')
  const dueDate = watch('due_date')
  const timing = useMemo(() => resolveTimingSettings(collectionSettings), [collectionSettings])
  const lifecycleMilestones = useMemo(() => {
    if (!issuedAt || !dueDate) return null
    return computeConcreteLifecycleMilestones({
      issuedAt,
      dueDate,
      dueSoonDays: timing.dueSoonDays,
      graceDays: selectedPolicy?.grace_days ?? 0,
    })
  }, [issuedAt, dueDate, timing, selectedPolicy])

  const mutation = useMutation({
    mutationFn: (values: ChargeBatchFormValues) => {
      const payload: Record<string, unknown> = {
        charge_policy_id: values.charge_policy_id,
        title: values.title,
        description: values.description || null,
        year: values.year,
        month: values.month,
        target_type: values.target_type,
        target_selector: buildTargetSelector(values),
        issued_at: values.issued_at,
        due_date: values.due_date,
        activate: values.activate,
      }
      return ChargeBatchResource.create(payload) as Promise<IChargeBatch>
    },
    onSuccess: () => {
      toast.success('Cobro creado')
      void queryClient.invalidateQueries({ queryKey: ['charges'] })
      navigate('/charge-batch')
    },
    onError: (error) => {
      toast.error(
        error instanceof ApiError ? formatApiErrorMessage(error) : 'No se pudo crear el cobro'
      )
    },
  })

  const isPending = mutation.isPending
  const policyIsAuto = selectedPolicy ? isAutoGenerated(selectedPolicy) : false

  return (
    <div className='mx-auto max-w-4xl space-y-6'>
      <div className='flex flex-wrap items-start justify-between gap-4'>
        <div>
          <Link
            to='/charge-batch'
            className='mb-1 inline-flex items-center gap-1 text-[12.5px] text-[var(--ink-3)] hover:text-foreground'
          >
            <ArrowLeft className='size-3.5' />
            Cobros programados
          </Link>
          <h1 className='text-[28px] font-semibold leading-[1.12] tracking-[-0.02em]'>
            Nuevo cobro
          </h1>
          <p className='mt-1.5 text-[13.5px] text-[var(--ink-3)]'>
            Genera un lote de cargos a partir de una programación de cobros.
          </p>
        </div>
      </div>

      <form onSubmit={handleSubmit((values) => mutation.mutate(values))} className='space-y-6'>
        <RequiredFieldsLegend />
        {/* Política + periodo */}
        <section className={SECTION}>
          <p className={SECTION_TITLE}>Programación y periodo</p>
          <FieldGroup>
            <div className='grid grid-cols-12 gap-4'>
              <Field className='col-span-12 md:col-span-6'>
                <FieldLabel htmlFor='batch-policy' required>
                  Programación de cobros
                </FieldLabel>
                <Controller
                  name='charge_policy_id'
                  control={control}
                  render={({ field }) => (
                    <SearchSelect<IChargePolicy>
                      id='batch-policy'
                      value={field.value}
                      onChange={(v) => field.onChange((v as string | null) ?? '')}
                      options={policies}
                      isDisabled={isPending}
                      invalid={!!errors.charge_policy_id}
                      placeholder='Seleccionar programación…'
                      getOptionLabel={(policy) => policyOptionLabel(policy)}
                    />
                  )}
                />
                <FieldError>{errors.charge_policy_id?.message}</FieldError>
              </Field>

              <MonthYearSelector
                control={control}
                register={register}
                errors={errors}
                disabled={isPending}
              />

              <Field className='col-span-12'>
                <PolicySummaryPanel policy={selectedPolicy} />
              </Field>

              {policyIsAuto && (
                <Field className='col-span-12'>
                  <Callout icon={RefreshCw}>
                    Esta programación se genera{' '}
                    <b className='font-semibold'>
                      automáticamente {periodicityCadenceLabel(selectedPolicy?.periodicity_id)}
                    </b>
                    . Usa este formulario solo para un cobro fuera de calendario (adelantar o
                    reemitir).
                  </Callout>
                </Field>
              )}

              <Field className='col-span-12'>
                <FieldLabel htmlFor='batch-title' required>
                  Título
                </FieldLabel>
                <Input
                  id='batch-title'
                  placeholder={`Ej. Mantenimiento ${month ? `${MONTH_NAMES[month - 1]} ` : ''}${year}`}
                  {...register('title')}
                  disabled={isPending}
                />
                <FieldDescription>Se autocompleta del concepto + periodo</FieldDescription>
                <FieldError>{errors.title?.message}</FieldError>
              </Field>

              <Field className='col-span-12'>
                <FieldLabel htmlFor='batch-desc'>Descripción</FieldLabel>
                <Textarea
                  id='batch-desc'
                  rows={2}
                  className='resize-none'
                  {...register('description')}
                  disabled={isPending}
                />
              </Field>
            </div>
          </FieldGroup>
        </section>

        {/* Alcance */}
        <section className={SECTION}>
          <p className={SECTION_TITLE}>Alcance</p>
          <FieldGroup className='gap-6'>
            <SingleTargetSelector
              control={control}
              register={register}
              errors={errors}
              targetType={targetType}
              targetUnitId={watch('target_unit_id')}
              targetUnitIds={watch('target_unit_ids') ?? []}
              catalogs={{
                unitTypes: catalogs[CatalogType.UNIT_TYPE] ?? [],
                towers: catalogs[CatalogType.TOWER] ?? [],
                sections: catalogs[CatalogType.SECTION] ?? [],
                features: catalogs[CatalogType.UNIT_FEATURE] ?? [],
              }}
              disabled={isPending}
              idPrefix='batch'
              singleUnitLabel={singleUnitLabel}
              onSingleUnitLabelChange={setSingleUnitLabel}
              onUnitSelect={(id) => setValue('target_unit_id', id, { shouldValidate: true })}
              onUnitIdsChange={(ids) => setValue('target_unit_ids', ids, { shouldValidate: true })}
              previewScope='charge-batch'
              previewSelector={previewSelector}
              previewFetcher={ChargeBatchResource.preview}
              previewNoun='unidades incluidas'
            />
          </FieldGroup>
        </section>

        {/* Fechas + ciclo de vida */}
        <section className={SECTION}>
          <p className={SECTION_TITLE}>Fechas</p>
          <div className='grid grid-cols-12 gap-4'>
            <Field className='col-span-6 md:col-span-4'>
              <FieldLabel htmlFor='batch-issued' required>
                Fecha de generación
              </FieldLabel>
              <Input
                id='batch-issued'
                type='date'
                {...register('issued_at')}
                disabled={isPending}
              />
              <FieldError>{errors.issued_at?.message}</FieldError>
            </Field>
            <Field className='col-span-6 md:col-span-4'>
              <FieldLabel htmlFor='batch-due' required>
                Vencimiento
              </FieldLabel>
              <Input id='batch-due' type='date' {...register('due_date')} disabled={isPending} />
              <FieldError>{errors.due_date?.message}</FieldError>
            </Field>
          </div>

          {lifecycleMilestones && (
            <div className='mt-4 rounded-[14px] border border-border bg-card p-4'>
              <p className={SECTION_TITLE}>Ciclo de vida del cobro</p>
              <ChargeLifecycleTimeline mode='concrete' milestones={lifecycleMilestones} />
            </div>
          )}
        </section>

        {/* Estado inicial */}
        <section className={SECTION}>
          <p className={SECTION_TITLE}>Estado inicial</p>
          <Field>
            <Controller
              name='activate'
              control={control}
              render={({ field }) => (
                <RadioGroup
                  value={field.value ? 'active' : 'draft'}
                  onValueChange={(v) => field.onChange(v === 'active')}
                  disabled={isPending}
                  className='flex flex-wrap gap-5'
                >
                  <label className='flex cursor-pointer items-center gap-2 text-[13px]'>
                    <RadioGroupItem value='active' />
                    Activo (genera cargos ya)
                  </label>
                  <label className='flex cursor-pointer items-center gap-2 text-[13px]'>
                    <RadioGroupItem value='draft' />
                    Borrador (revisar antes de activar)
                  </label>
                </RadioGroup>
              )}
            />
          </Field>
        </section>

        <div className='flex justify-end gap-2 border-t border-border pt-4'>
          <Button
            type='button'
            variant='outline'
            onClick={() => navigate('/charge-batch')}
            disabled={isPending}
          >
            Cancelar
          </Button>
          <Button type='submit' disabled={isPending} className='min-w-[130px]'>
            {isPending ? 'Creando…' : 'Crear cobro'}
          </Button>
        </div>
      </form>
    </div>
  )
}
